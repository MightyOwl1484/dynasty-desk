import { readFile } from 'node:fs/promises';

const html = await readFile('dist/index.html', 'utf8');
const script = await readFile('dist/app.js', 'utf8');

const checks = [
  ['classic deferred script', /<script src="app\.js" defer><\/script>/],
  ['club picker', /id="clubPicker"/],
  ['club preview', /id="clubPreview"[^>]*aria-live="polite"/],
  ['guided tour', /<dialog id="tourDialog"[^>]*aria-labelledby="tourTitle"/],
  ['tour can be reopened', /id="openTour"/]
];

const missing = checks.filter(([, pattern]) => !pattern.test(html)).map(([name]) => name);
if (missing.length) throw new Error(`Browser build checks failed: ${missing.join(', ')}`);
if (/^\s*import\s/m.test(script) || /\bexport\s+(const|function|class|\{)/.test(script)) {
  throw new Error('dist/app.js must be self-contained so index.html can run from file://.');
}
if (!script.includes('Generated by scripts/build.mjs')) throw new Error('dist/app.js is not the generated browser bundle.');
if (!script.includes('id="trainingSelect"') || !script.includes('id="trainingHelp" role="status" aria-live="polite"')) {
  throw new Error('The generated game is missing the accessible weekly training control.');
}
if (!html.includes('id="captainSelect"') || !script.includes('Form steady')) {
  throw new Error('The generated game is missing captaincy or player-form controls.');
}
if (!script.includes('id="applyScoutTactic"') || !script.includes('id="applyRotation"')) {
  throw new Error('The generated game is missing scouting or rotation recommendations.');
}
if (!html.includes('id="boardConfidence"') || !script.includes('boardEvaluation()')) {
  throw new Error('The generated game is missing season objectives or board confidence.');
}
if (!html.includes('id="academyCandidates"') || !script.includes('data-prospect=')) {
  throw new Error('The generated game is missing the youth intake selection.');
}

console.log(`Browser build checks passed (${checks.length + 5} interface checks, self-contained script).`);
